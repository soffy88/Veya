"""cli/product.py — veya 产品化入口 (init / start / doctor)。

把「框架」变成「产品」的最小闭环:
  veya init    首次运行向导: 接模型 → 选工作目录 → 生成开箱配置 → 给示例任务
  veya start   一键启动本地服务 (HTTP + SSE), 自动打开浏览器
  veya doctor  环境自检: 版本 / Key / 本地模型 / 工作区 / 端口

配置落点 (与 config.loader 消费路径一致):
  ~/.veya/config.json   主配置 (loader._default_paths 第 2 优先)
  ~/.veya/.env          API Key 文件 (chmod 600, 不落盘明文于仓库)
  工作区 .env           用户可见/可编辑的 Key 副本 (loader 读 cwd .env)
  工作区 .veya/security.yaml  安全策略 (allowed_paths 绑定工作区)
"""

from __future__ import annotations

import contextlib
import getpass
import json
import os
import sys
import webbrowser
from pathlib import Path
from typing import Any

_HOME_DIR = Path.home() / ".veya"
_CONFIG_PATH = _HOME_DIR / "config.json"
_ENV_PATH = _HOME_DIR / ".env"

PROVIDERS: dict[str, dict[str, str]] = {
    "openai": {"name": "OpenAI", "env": "OPENAI_API_KEY", "model": "gpt-4o-mini"},
    "anthropic": {"name": "Anthropic", "env": "ANTHROPIC_API_KEY", "model": "claude-sonnet-4-20250514"},
    "dashscope": {"name": "阿里云 DashScope", "env": "DASHSCOPE_API_KEY", "model": "qwen-plus"},
    "deepseek": {"name": "DeepSeek", "env": "DEEPSEEK_API_KEY", "model": "deepseek-chat"},
    "ollama": {"name": "Ollama (本地)", "env": "", "model": None},
}

OLLAMA_BASE = "http://localhost:11434"
OLLAMA_ENDPOINT = f"{OLLAMA_BASE}/v1/chat/completions"

SECURITY_TEMPLATE = """\
# Security policy generated by `veya init` — edit freely.
# 危险操作(写文件/外部 API/Shell)默认受限, 需要时在对话中确认或放宽此处。
default_permissions:
  - read_files
  - execute_code
  - network_connect

restricted_permissions:
  - write_files
  - call_external_api
  - shell_execute

audit_enabled: true
log_file: "security_audit.log"

whitelist:
  allowed_hosts:
    - "localhost"
    - "127.0.0.1"
    - "::1"
  allowed_paths:
    - "{workspace}"
    - "/tmp/"

blacklist:
  forbidden_patterns:
    - "../"
"""


