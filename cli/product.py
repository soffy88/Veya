def run_doctor(argv: list[str]) -> int:
    """veya doctor — 环境自检 (可脚本化, 输出检查清单)。"""
    import argparse

    p = argparse.ArgumentParser(prog="veya doctor", description="环境自检")
    p.add_argument("--json", action="store_true", help="JSON 输出 (脚本友好)")
    args = p.parse_args(argv)

    import platform

    checks: list[dict[str, Any]] = []
    ok = True

    def add(name: str, passed: bool, detail: str = "") -> None:
        nonlocal ok
        checks.append({"name": name, "ok": bool(passed), "detail": detail})
        ok = ok and bool(passed)

    # Python / veya 版本
    py_ok = sys.version_info >= (3, 11)
    add("python>=3.11", py_ok, platform.python_version())
    try:
        import veya  # noqa: F401

        ver = "veya 0.6.0"
    except ImportError:
        ver = "未安装 (请 pip install veya)"
    add("veya 已安装", "veya 0.6.0" in ver or "not" not in ver, ver)

    # 配置
    cfg = _load_config()
    add("~/.veya/config.json", bool(cfg), str(_CONFIG_PATH) if cfg else "运行 `veya init` 生成")

    # 模型接入
    provider = (cfg.get("llm") or {}).get("provider", "")
    if provider == "ollama":
        models = probe_ollama()
        add("Ollama 本地模型", models is not None,
            f"{OLLAMA_BASE} → {', '.join(models[:4])}" if models else "不可达")
    elif provider:
        meta = PROVIDERS.get(provider)
        env = meta["env"] if meta else f"{provider.upper()}_API_KEY"
        key = (cfg.get("providers") or {}).get(provider, {}).get("api_key") if isinstance(
            (cfg.get("providers") or {}).get(provider), dict
        ) else ""
        key = key or os.environ.get(env, "")
        add(f"模型接入 ({provider})", bool(key),
            f"{env} 已配置" if key else f"未配置 {env} — 运行 `veya init` 或 export {env}")
    else:
        add("模型接入", False, "未配置 provider — 运行 `veya init`")

    # 工作区
    ws = cfg.get("workspace", "")
    ws_ok = bool(ws) and Path(ws).is_dir()
    add("工作区", ws_ok, ws if ws_ok else "未配置或目录不存在 — 运行 `veya init`")

    # 端口
    port_busy = _port_in_use(8765)
    add("端口 8765", not port_busy, "空闲" if not port_busy else "被占用 (veya start 可用 --port 换端口)")

    if args.json:
        print(json.dumps({"ok": ok, "checks": checks}, ensure_ascii=False, indent=2))
        return 0 if ok else 1

    print("veya doctor — 环境自检")
    for c in checks:
        mark = "✔" if c["ok"] else "✗"
        print(f"  {mark} {c['name']}: {c['detail']}")
    print(f"\n结论: {'一切就绪, 运行 `veya start` 开干' if ok else '有 N 项需处理, 按提示修复后重试'}"
          .replace("N", str(sum(1 for c in checks if not c["ok"]))))
    return 0 if ok else 1


def _port_in_use(port: int) -> bool:
    import socket

    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
        s.settimeout(0.3)
        try:
            s.bind(("127.0.0.1", port))
            return False
        except OSError:
            return True


