def _ask(prompt: str, default: str = "") -> str:
    suffix = f" [{default}]" if default else ""
    raw = input(f"{prompt}{suffix}: ").strip()
    return raw or default


def _choose(prompt: str, options: list[str]) -> str:
    for i, opt in enumerate(options, 1):
        print(f"  {i}) {opt}")
    while True:
        raw = input(f"{prompt} (1-{len(options)}): ").strip()
        if raw.isdigit() and 1 <= int(raw) <= len(options):
            return options[int(raw) - 1]
        print("  输入无效, 请重试。")


def run_init(argv: list[str]) -> int:
    """veya init — 首次运行向导 (支持全 flags 非交互)。"""
    import argparse

    p = argparse.ArgumentParser(prog="veya init", description="首次运行向导")
    p.add_argument("--provider", choices=list(PROVIDERS), help="模型提供商 (ollama=本地)")
    p.add_argument("--key", default=None, help="API Key (非交互模式)")
    p.add_argument("--model", default=None, help="模型名 (缺省用该提供商默认)")
    p.add_argument("--workspace", default=None, help="工作目录 (Agent 读写范围)")
    p.add_argument("--yes", action="store_true", help="非交互: 全部使用默认值/给定 flags")
    args = p.parse_args(argv)

    interactive = not args.yes

    print("=" * 56)
    print("  veya — 首次运行向导")
    print("  3 步接好: 模型 → 工作目录 → 直接开干")
    print("=" * 56)

    # ── 1. 模型 ──────────────────────────────────────────────────
    provider = args.provider
    if provider is None:
        print("\n[1/3] 选择模型提供商:")
        if interactive:
            options = list(PROVIDERS)
            provider = _choose("选择", options)
        else:
            provider = "openai"

    meta = PROVIDERS[provider]
    if provider == "ollama":
        models = probe_ollama()
        if models is None:
            print(
                f"\n⚠  未检测到本地 Ollama ({OLLAMA_BASE})。\n"
                "    请先安装并启动: https://ollama.com\n"
                "    完成后重新运行 `veya init` 或直接编辑 ~/.veya/config.json。"
            )
            if not interactive:
                print("    已跳过 (可在 config.json 中手动配置 VEYA_LLM_ENDPOINT)。")
        elif not models:
            print("\n⚠  Ollama 已启动但没有模型。请先: ollama pull qwen2.5:7b")
        else:
            print(f"\n✔  检测到本地 Ollama, 可用模型: {', '.join(models[:6])}")
        model = args.model or "qwen2.5:7b"
    else:
        print(f"\n[1/3] 提供商: {meta['name']} ({meta['env']})")
        model = args.model or meta["model"]

    # ── 2. API Key ───────────────────────────────────────────────
    key = args.key
    if provider != "ollama":
        if key is None:
            if interactive:
                key = getpass.getpass(f"  粘贴 {meta['env']} (输入为空则跳过, 用离线 stub): ")
            else:
                key = os.environ.get(meta["env"], "")
        if not key:
            print("  ⚠  未提供 Key — 将以离线 stub 模式运行 (仅体验流程, 不调用真实模型)。")

    # ── 3. 工作目录 ──────────────────────────────────────────────
    print("\n[2/3] 工作目录 (Agent 的文件读写与命令执行范围):")
    workspace = args.workspace
    if workspace is None:
        default_ws = str(Path.cwd())
        workspace = default_ws if not interactive else _ask("  输入工作目录", default_ws)
    ws = Path(workspace).expanduser().resolve()
    if not ws.is_dir():
        print(f"  ✗ 目录不存在: {ws}")
        return 1
    print(f"  ✔  工作区: {ws}")

    # ── 写入配置 ─────────────────────────────────────────────────
    config = _load_config()
    config.setdefault("llm", {})["provider"] = provider
    if model:
        config["llm"]["model"] = model
    if provider != "ollama" and key:
        config.setdefault("providers", {})[provider] = {"api_key": key}
    config["workspace"] = str(ws)
    config["persona"] = "build"
    _save_config(config)

    if provider != "ollama" and key:
        _write_env_file(_ENV_PATH, meta["env"], key)
        _write_env_file(ws / ".env", meta["env"], key)
        print(f"\n  ✔  Key 已写入 {_ENV_PATH} (chmod 600) 与 {ws / '.env'}")

    # 工作区安全策略
    sec_dir = ws / ".veya"
    sec_dir.mkdir(parents=True, exist_ok=True)
    sec_file = sec_dir / "security.yaml"
    if not sec_file.exists():
        sec_file.write_text(SECURITY_TEMPLATE.format(workspace=str(ws)), encoding="utf-8")
        print(f"  ✔  安全策略已生成: {sec_file} (危险操作默认受限, 可在对话中确认)")

    print("\n[3/3] 完成 ✔")
    print("\n下一步:")
    if provider == "ollama":
        print(f"  export VEYA_LLM_ENDPOINT={OLLAMA_ENDPOINT}")
        print("  (或写入工作区 .env: VEYA_LLM_ENDPOINT=http://localhost:11434/v1/chat/completions)")
    print("  veya start                 # 启动本地服务 + 打开浏览器")
    print('  veya "帮我把当前目录的 README 改得更产品化"   # 直接派任务')
    print('  或: veya-headless --agent plan --text "你的任务"')
    return 0


